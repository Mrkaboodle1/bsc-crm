#!/usr/bin/env node
// Reads media-catalog.json (local-only, contains absolute paths) and emits a
// privacy-safe stats summary as app/src/data/media-stats.ts that the deployed
// app can import. NO absolute paths in the output — only counts + buckets.

import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CATALOG = path.join(PROJECT_ROOT, 'media-catalog.json')
const OUT = path.join(PROJECT_ROOT, 'app/src/data/media-stats.ts')

const raw = await fs.readFile(CATALOG, 'utf8')
const cat = JSON.parse(raw)
const items = Object.values(cat.items)

const images = items.filter((i) => i.kind === 'image')
const videos = items.filter((i) => i.kind === 'video')
const heicImages = images.filter((i) => i.ext === 'heic' || i.ext === 'heif').length
const totalBytes = items.reduce((sum, i) => sum + i.size, 0)

// Distribution by year (from mtime)
const byYear = {}
for (const i of items) {
  const year = new Date(i.mtime).getFullYear()
  byYear[year] = (byYear[year] ?? 0) + 1
}

// Top folders (by relative path's first 2 segments)
const folders = {}
for (const i of items) {
  // Pull a folder name from the absolute path — but only the leaf folder
  // (don't expose drive letters or full home paths)
  const parts = i.path.split(/[\\/]/).filter(Boolean)
  // Last 2 path segments minus the file name
  const folderKey = parts.slice(-3, -1).join(' / ') || 'root'
  folders[folderKey] = (folders[folderKey] ?? 0) + 1
}
const topFolders = Object.entries(folders)
  .sort((a, b) => b[1] - a[1])
  .slice(0, 12)
  .map(([name, count]) => ({ name, count }))

// Duplicate sets
const byHash = new Map()
for (const i of items) {
  if (!byHash.has(i.sha256)) byHash.set(i.sha256, [])
  byHash.get(i.sha256).push(i)
}
let dupSets = 0
let dupExtras = 0
let dupBytes = 0
for (const group of byHash.values()) {
  if (group.length > 1) {
    dupSets++
    dupExtras += group.length - 1
    dupBytes += group[0].size * (group.length - 1)
  }
}

// Format examples for the table
const recentExamples = items
  .filter((i) => i.kind === 'image')
  .sort((a, b) => b.mtime - a.mtime)
  .slice(0, 8)
  .map((i) => ({
    name: path.basename(i.path),
    ext: i.ext,
    sizeKB: Math.round(i.size / 1024),
    mtime: i.mtime_iso,
    sha8: i.sha256.slice(0, 8),
  }))

const stats = {
  generatedAt: cat.generated_at,
  totalItems: items.length,
  totalImages: images.length,
  totalVideos: videos.length,
  totalHeic: heicImages,
  totalBytes,
  totalGB: +(totalBytes / 1024 ** 3).toFixed(2),
  byYear,
  topFolders,
  dupSets,
  dupExtras,
  dupBytes,
  dupGB: +(dupBytes / 1024 ** 3).toFixed(2),
  recentExamples,
}

const tsContent = `// AUTO-GENERATED by scripts/generate-media-stats.mjs — do not edit by hand.
// Source: media-catalog.json (kept locally; this file is the privacy-safe
// summary that's safe to deploy.)

export const mediaStats = ${JSON.stringify(stats, null, 2)} as const

export type MediaStats = typeof mediaStats
`

await fs.mkdir(path.dirname(OUT), { recursive: true })
await fs.writeFile(OUT, tsContent, 'utf8')

console.log(`✅ Wrote ${OUT}`)
console.log(`   Items: ${stats.totalItems} (${stats.totalImages} images, ${stats.totalVideos} videos)`)
console.log(`   Size: ${stats.totalGB} GB`)
console.log(`   Dupes: ${stats.dupSets} sets, ${stats.dupExtras} extras, ${stats.dupGB} GB of repetition`)
console.log(`   Top folder: ${topFolders[0]?.name} (${topFolders[0]?.count} items)`)
