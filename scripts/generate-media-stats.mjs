#!/usr/bin/env node
// Reads media-catalog.json and emits a privacy-safe summary the app can use.

import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CATALOG = path.join(PROJECT_ROOT, 'media-catalog.json')
const OUT_STATS = path.join(PROJECT_ROOT, 'app/src/data/media-stats.ts')
const OUT_LIBRARY = path.join(PROJECT_ROOT, 'app/src/data/media-library.ts')

const raw = await fs.readFile(CATALOG, 'utf8')
const cat = JSON.parse(raw)
const items = Object.values(cat.items)

const images = items.filter((i) => i.kind === 'image')
const videos = items.filter((i) => i.kind === 'video')
const heicImages = images.filter((i) => i.ext === 'heic' || i.ext === 'heif').length
const totalBytes = items.reduce((sum, i) => sum + i.size, 0)

const byYear = {}
for (const i of items) {
  const year = new Date(i.mtime).getFullYear()
  byYear[year] = (byYear[year] ?? 0) + 1
}

const folders = {}
for (const i of items) {
  const parts = i.path.split(/[\\/]/).filter(Boolean)
  const folderKey = parts.slice(-3, -1).join(' / ') || 'root'
  folders[folderKey] = (folders[folderKey] ?? 0) + 1
}
const topFolders = Object.entries(folders)
  .sort((a, b) => b[1] - a[1])
  .slice(0, 12)
  .map(([name, count]) => ({ name, count }))

const byHash = new Map()
for (const i of items) {
  if (!byHash.has(i.sha256)) byHash.set(i.sha256, [])
  byHash.get(i.sha256).push(i)
}
let dupSets = 0
let dupExtras = 0
let dupBytes = 0
const dupGroups = []
for (const group of byHash.values()) {
  if (group.length > 1) {
    dupSets++
    dupExtras += group.length - 1
    dupBytes += group[0].size * (group.length - 1)
    if (dupGroups.length < 100) {
      dupGroups.push({
        sha8: group[0].sha256.slice(0, 8),
        count: group.length,
        size: group[0].size,
        files: group.map((g) => path.basename(g.path)),
      })
    }
  }
}

const recentExamples = items
  .filter((i) => i.kind === 'image')
  .sort((a, b) => b.mtime - a.mtime)
  .slice(0, 8)
  .map((i) => ({
    name: path.basename(i.path),
    ext: i.ext,
    sizeKB: Math.round(i.size / 1024),
    mtime: i.mtime_iso,
    sha8: i.sha256.slice(0, 8),
  }))

const stats = {
  generatedAt: cat.generated_at,
  totalItems: items.length,
  totalImages: images.length,
  totalVideos: videos.length,
  totalHeic: heicImages,
  totalBytes,
  totalGB: +(totalBytes / 1024 ** 3).toFixed(2),
  byYear,
  topFolders,
  dupSets,
  dupExtras,
  dupBytes,
  dupGB: +(dupBytes / 1024 ** 3).toFixed(2),
  recentExamples,
}

// Library: ALL items with metadata. Trim heavy fields. Strip absolute paths.
const library = items.map((i) => {
  const parts = i.path.split(/[\\/]/).filter(Boolean)
  const folder = parts.slice(-3, -1).join('/')
  return {
    sha: i.sha256.slice(0, 16),
    sha8: i.sha256.slice(0, 8),
    name: parts[parts.length - 1],
    folder,
    kind: i.kind,
    ext: i.ext,
    sizeKB: Math.round(i.size / 1024),
    mtime: i.mtime_iso.slice(0, 10),
  }
}).sort((a, b) => b.mtime.localeCompare(a.mtime))

const statsTs = `// AUTO-GENERATED by scripts/generate-media-stats.mjs.
export const mediaStats = ${JSON.stringify(stats, null, 2)} as const
export const duplicateGroups = ${JSON.stringify(dupGroups, null, 2)} as const
export type MediaStats = typeof mediaStats
`

const libraryTs = `// AUTO-GENERATED by scripts/generate-media-stats.mjs.
// Privacy-safe library catalog — no absolute paths.
export type LibraryItem = {
  sha: string
  sha8: string
  name: string
  folder: string
  kind: 'image' | 'video'
  ext: string
  sizeKB: number
  mtime: string
}

export const mediaLibrary: ReadonlyArray<LibraryItem> = ${JSON.stringify(library, null, 0)}
`

await fs.mkdir(path.dirname(OUT_STATS), { recursive: true })
await fs.writeFile(OUT_STATS, statsTs, 'utf8')
await fs.writeFile(OUT_LIBRARY, libraryTs, 'utf8')

console.log(`✅ ${OUT_STATS}`)
console.log(`✅ ${OUT_LIBRARY} (${library.length} items)`)
console.log(`   ${stats.totalItems} items, ${stats.totalGB} GB, ${stats.dupSets} dup sets`)
